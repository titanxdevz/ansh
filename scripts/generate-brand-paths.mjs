/**
 * Generates `src/lib/brand-paths.ts` from the local `simple-icons` package.
 *
 * The published `simple-icons` entry point is a 5 MB module of 3,467 icons.
 * Importing it into a client bundle means the parser and bundler chew through
 * all of it before tree shaking removes what we did not ask for. This script
 * copies the handful of paths this site actually renders into a small file
 * with zero runtime dependency.
 *
 * Run with: node scripts/generate-brand-paths.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const iconsDir = resolve(here, "..", "node_modules", "simple-icons", "icons");

const SLUGS = [
  "javascript",
  "typescript",
  "python",
  "rust",
  "php",
  "ejs",
  "discord",
  "discorddotjs",
  "react",
  "nextdotjs",
  "tailwindcss",
  "express",
  "postman",
  "nodedotjs",
  "sqlite",
  "mongodb",
  "mongoose",
  "mysql",
  "prisma",
  "pterodactyl",
  "cloudflare",
  "maildotcom",
  "serverless",
  "laravel",
  "android",
  "google",
  "anthropic",
  "youtube",
  "vercel",
  "vite",
  "svelte",
  "docker",
  "postgresql",
  "linux",
  "github",
  "git",
  "githubactions",
  "figma",
  "googlecloud",
  "firebase",
];

const entries = [];

for (const slug of SLUGS) {
  const svg = await readFile(resolve(iconsDir, `${slug}.svg`), "utf8");
  const pathMatch = svg.match(/<path d="([^"]+)"/);
  const titleMatch = svg.match(/<title>([^<]+)<\/title>/);
  if (!pathMatch) {
    throw new Error(`No <path> found for slug "${slug}"`);
  }
  entries.push({
    slug,
    title: titleMatch ? titleMatch[1] : slug,
    d: pathMatch[1],
  });
}

const body = entries
  .map((e) => `  ${e.slug}: {\n    title: ${JSON.stringify(e.title)},\n    d: ${JSON.stringify(e.d)},\n  },`)
  .join("\n");

const file = `// Generated by scripts/generate-brand-paths.mjs. Do not edit by hand.
// Source: simple-icons (CC0). Regenerate after changing the slug list.

export type BrandIconData = {
  title: string;
  d: string;
};

export const brandPaths: Record<string, BrandIconData> = {
${body}
};
`;

await writeFile(resolve(here, "..", "src", "lib", "brand-paths.ts"), file, "utf8");

console.log(`Wrote ${entries.length} brand paths to src/lib/brand-paths.ts`);
